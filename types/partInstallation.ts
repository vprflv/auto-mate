export function getPartInstallationFields(name: string): {
    axle: boolean;
    side: boolean;
} {
    const normalized = name
        .toLowerCase()
        .replace(/ё/g, 'е')
        .replace(/[^\p{L}\p{N}]+/gu, ' ')
        .trim();

    // Пробелы по краям позволяют искать целые слова и в начале,
    // и в конце названия.
    const text = ` ${normalized} `;

    const matches = INSTALLATION_RULES.filter(rule =>
        rule.names.some(pattern => pattern.test(text))
    );

    return {
        axle: matches.some(rule => rule.axle),
        side: matches.some(rule => rule.side),
    };
}