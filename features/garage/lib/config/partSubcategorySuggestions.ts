export function getPartSubcategorySuggestions(
    categoryId: string,
    categoryLabel: string
): string[] {
    const key =
        CATEGORY_NAMES[normalize(categoryLabel)] ??
        categoryId;

    return SUGGESTIONS[key] ?? [];
}

export function isSuggestedPartSubcategory(
    name: string,
    suggestions: string[]
): boolean {
    const normalized = normalize(name);

    return suggestions.some(
        (suggestion) => normalize(suggestion) === normalized
    );
}